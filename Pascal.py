def pascal_triangle(n):  # рекурсивная функция для построения треугольника Паскаля
    if n == 0:  # если 0, то возвращаем пустой список
        return []
    if n == 1:  # если 1, то возвращаем первый ряд
        return [[1]]
    
    prev = pascal_triangle(n - 1)  # рекурсивно получаем треугольник до предыдущего уровня
    last_row = prev[-1]  # берем последнюю строку из предыдущего треугольника
    new_row = [1] + [last_row[i] + last_row[i + 1] for i in range(len(last_row) - 1)] + [1] # создаем новую строку: начинаем с 1, складываем соседние элементы, заканчиваем 1
    return prev + [new_row]  # добавляем новую строку к предыдущим и возвращаем

level = int(input("введите количество строк: "))  # вводим количество строк
result = pascal_triangle(level)  # вызываем функцию для построения треугольника
for row in result:  # перебираем все строки
    print(row)  # выводим каждую строку на экран