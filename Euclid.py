def NOD(a, b):  # рекурсивная функция для нахождения НОД 
    if b == 0:  # усли второе число = 0
        return a  # возвращаем первое число, оно же НОД
    return NOD(b, a % b)  # рекурсивный шаг, мы передаем b и остаток от деления a на b

num1 = int(input("ввести первое число: "))  # вводим первое число
num2 = int(input("ввести второе число: "))  # вводим второе число
print(f"НОД({num1}, {num2}) = {NOD(num1, num2)}")  # вывод результата 